// The fleet view (spec Sections 19, 21): one row per station, the six signals each drawn against that
// station's own normal. Colour carries state only — neutral in control, amber in drift, dotted grey while
// learning a baseline, red when offline. A value is never shown without its limit.
import { useEffect, useState } from 'react';
import { Line, LineChart, ReferenceLine, ResponsiveContainer, YAxis } from 'recharts';
import { fleet } from '../lib/api';
import type { FleetStation, SignalChart } from '../lib/types';

const SIGNALS = ['ip_conf_mean', 'ambiguous_rate', 'anchor_residual_px', 'evidence_p99_ms', 'dropped_frame_rate', 'sm_clock_ratio'];

function Spark({ c, offline }: { c?: SignalChart; offline: boolean }) {
  if (!c || !c.series.length) return <div className="grid h-14 place-items-center text-[11px] text-muted">no data</div>;
  const stroke = offline ? 'var(--state-fault)' : c.state === 'drift' ? 'var(--state-active)' : c.state === 'baseline' ? '#6b7280' : 'var(--text-muted)';
  const last = c.series[c.series.length - 1]?.v;
  return (
    <div className="h-14" data-state={c.state}>
      <ResponsiveContainer width="100%" height="78%">
        <LineChart data={c.series} margin={{ top: 2, bottom: 2, left: 0, right: 0 }}>
          <YAxis hide domain={['auto', 'auto']} />
          {c.center != null && <ReferenceLine y={c.center} stroke="var(--line)" />}
          {c.limit != null && <ReferenceLine y={c.limit} stroke="var(--state-active)" strokeDasharray="3 3" />}
          <Line dataKey="v" stroke={stroke} dot={false} strokeWidth={1.6} strokeDasharray={c.state === 'baseline' ? '2 3' : undefined} isAnimationActive={false} />
        </LineChart>
      </ResponsiveContainer>
      <div className="mono whitespace-nowrap text-[10px] text-muted" title="latest bucket / control limit">
        {last != null ? last.toFixed(3) : '—'} {c.limit != null ? `· lim ${c.limit.toFixed(3)}` : '· learning'}
      </div>
    </div>
  );
}

export function Fleet() {
  const [rows, setRows] = useState<FleetStation[]>([]);
  const [hours, setHours] = useState(24 * 30);
  useEffect(() => {
    let live = true;
    const load = () => fleet(hours).then((r) => live && setRows(r)).catch(() => {});
    load();
    const t = setInterval(load, 10000);
    return () => {
      live = false;
      clearInterval(t);
    };
  }, [hours]);
  const attention = rows.filter((r) => r.drifting.length || r.engine_up === false);
  const synthetic = rows.some((r) => r.synthetic);
  return (
    <div className="p-4">
      <div className="mb-3 flex items-center justify-between">
        <h1 style={{ font: 'var(--t-h1)' }}>Fleet health</h1>
        <select value={hours} onChange={(e) => setHours(Number(e.target.value))} className="mono rounded border border-line bg-surface px-2 py-1">
          <option value={24}>24 h</option><option value={24 * 7}>7 days</option><option value={24 * 30}>30 days</option>
        </select>
      </div>
      {synthetic && (
        <div className="mb-3 rounded-md border border-active/50 bg-active/10 px-3 py-2 text-active" data-testid="synthetic-banner">
          SEEDED SYNTHETIC HISTORY — generated by scripts/seed_history.py to show drift detection, not measured on a line.
        </div>
      )}
      <div className="panel mb-4 p-3">
        <h2 className="zone-title mb-2">Attention</h2>
        {!attention.length && <div className="text-muted">Every station inside its limits.</div>}
        {attention.map((r) => (
          <div key={r.station_id} className="mb-1.5 flex flex-wrap items-baseline gap-2" data-attention={r.station_id}>
            <span className="font-semibold">{r.station_id}</span>
            {r.engine_up === false ? <span className="text-fault">engine offline</span> : (
              <>
                <span className="mono text-active">{r.drifting.join(' + ')}</span>
                <span>→ likely <b>{r.diagnosis?.likely_cause}</b>; {r.diagnosis?.action}.</span>
              </>
            )}
          </div>
        ))}
      </div>
      <div className="panel overflow-x-auto">
        <table className="w-full min-w-[1100px] border-collapse">
          <thead>
            <tr className="text-left text-[12px] text-muted">
              <th className="p-2">station</th><th className="p-2">engine</th><th className="p-2">model · CAD</th>
              {SIGNALS.map((s) => <th key={s} className="mono p-2 font-normal">{s}</th>)}
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.station_id} className="border-t border-line align-top" data-station={r.station_id}>
                <td className="p-2 font-semibold">{r.station_id}{r.canary && <span className="ml-1.5 rounded bg-info/30 px-1.5 text-[11px]">canary</span>}</td>
                <td className="p-2">{r.engine_up === false ? <span className="text-fault">offline</span> : r.engine_up ? <span className="text-ok">up</span> : '—'}</td>
                <td className="mono p-2 text-[12px] text-muted">{r.model_version ?? '—'}<br />{r.cad_revision ?? ''}</td>
                {SIGNALS.map((s) => <td key={s} className="w-[150px] p-2"><Spark c={r.signals[s]} offline={r.engine_up === false} /></td>)}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
